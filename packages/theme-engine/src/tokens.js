/* ==========================================================================
   Token output
   Turns a palette into the `color` block of tokens/1-global.json (W3C DTCG).
   $value stays hex, so Figma, Tokens Studio and the blog's Sass work
   unchanged; the OKLCH each step was built from goes in $extensions.
   ========================================================================== */

import { STEPS } from './ramp.js';

export const EXTENSION = 'com.designforhumans.theme-engine';

const order = (steps) =>
  [...steps].sort((a, b) => Number(a) - Number(b) || a.localeCompare(b));

/**
 * Returns a new `color` block: the non-ramp colours of `current` (its $type,
 * transparent, black, white) followed by one group per hue in the palette.
 */
export const colorBlock = (palette, current = {}) => {
  const block = {};
  for (const [key, value] of Object.entries(current)) {
    const isRamp = value && typeof value === 'object' && !('$value' in value);
    if (!isRamp) block[key] = value;
  }
  block.$description = 'Generated by the theme engine from tokens/theme.json (npm run build:palette -- --write). Edit the theme, not these values.';
  for (const [hue, ramp] of Object.entries(palette)) {
    block[hue] = {};
    for (const step of order(Object.keys(ramp))) {
      const s = ramp[step];
      block[hue][step] = { $value: s.hex, $extensions: { [EXTENSION]: { oklch: s.oklch } } };
    }
  }
  return block;
};

/**
 * Returns `global` with the theme's fixed colours (white, black) in place
 * of the file's, so the gate and the token output use the theme's.
 */
export const withFixed = (global, theme) => {
  if (!theme?.fixed) return global;
  const color = { ...global.color };
  for (const [name, hex] of Object.entries(theme.fixed)) color[name] = { ...color[name], $value: hex };
  return { ...global, color };
};

export { STEPS };
