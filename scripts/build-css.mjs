#!/usr/bin/env node
/* ==========================================================================
   npm run build:css
   Builds the library for sites that link it from the docs domain
   (components.designforhumans.blog/css/<version>/):
   - dfh-components.css: index.css and everything it imports, in one
     minified file, with the cascade layers as index.css declares them
   - themes/<name>.css: each theme's and sub-brand's stylesheet, minified
   - fonts.css: the default theme's stored fonts, when it has any
   The version is packages/css/package.json's. A published version never
   changes, so a site pinned to it keeps what it was tested with: when the
   files would differ from what's already there, the build stops and asks
   for a new version. Run build:themes first.

   npm run build:css -- --out <dir> writes a working build to <dir> instead,
   for trying unreleased changes on a site (point its DFH_COMPONENTS_CSS at
   it). It has no version, and the published-version check is skipped.
   ========================================================================== */

import { bundle, transform } from 'lightningcss';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'packages/css/src');
const { version } = JSON.parse(readFileSync(join(src, '../package.json'), 'utf8'));
const outFlag = process.argv.indexOf('--out');
const working = outFlag > -1 ? resolve(process.argv[outFlag + 1] ?? '') : null;
if (working === root || (outFlag > -1 && !process.argv[outFlag + 1])) throw new Error('--out needs a folder');
const out = working ?? join(root, 'packages/docs/public/css', version);
const relative = (p) => (p.startsWith(root) ? p.slice(root.length + 1) : p);

/* Lightning CSS keeps @function (it warns that it doesn't know it) but
   drops the layer order statement, so it goes back at the top. The order
   comes from index.css, so the two can't drift. */
const index = readFileSync(join(src, 'index.css'), 'utf8');
const order = index.match(/^@layer [^;{]+;/m)?.[0];
if (!order) throw new Error('index.css has no @layer order statement');
/* …and passes anchored() container queries through untouched, with a warning too */
const quiet = (warnings) => warnings.filter((w) => !/Unknown at rule: @function|Function\("anchored"\)/.test(w.message));
const report = (file, warnings) => quiet(warnings).forEach((w) => console.warn(`⚠️  ${file}: ${w.message}${w.loc ? ` (${relative(w.loc.filename)}:${w.loc.line})` : ''}`));

const head = (what) => `/* Design For Humans ${working ? `${version}+working` : version}: ${what}. Generated by npm run build:css; https://components.designforhumans.blog */\n`;
const files = {};

const lib = bundle({ filename: join(src, 'index.css'), minify: true, errorRecovery: true });
report('dfh-components.css', lib.warnings);
files['dfh-components.css'] = `${head('the library')}${order}${lib.code}`;

const minify = (file) => {
  const css = transform({ filename: file, code: readFileSync(file), minify: true, errorRecovery: true });
  report(relative(file), css.warnings);
  return css.code.toString();
};
for (const name of readdirSync(join(src, 'themes')).filter((f) => f.endsWith('.css')).sort()) {
  /* The theme's own opening comment says how to link it and which fonts it needs: keep it */
  const text = readFileSync(join(src, 'themes', name), 'utf8');
  const note = text.match(/^\/\*[\s\S]*?\*\//)?.[0] ?? '';
  files[`themes/${name}`] = `${note}\n${minify(join(src, 'themes', name))}`;
}
const fonts = minify(join(src, 'fonts.css'));
if (fonts.trim()) files['fonts.css'] = `${head('the default theme\'s fonts')}${fonts}`;

/* A published version never changes */
const changed = working ? [] : Object.entries(files).filter(([file, css]) => existsSync(join(out, file)) && readFileSync(join(out, file), 'utf8') !== css);
if (changed.length) {
  console.error(`✖ ${version} is already published, and ${changed.map(([f]) => f).join(', ')} would change. Raise the version in packages/css/package.json.`);
  process.exit(1);
}
for (const [file, css] of Object.entries(files)) {
  mkdirSync(dirname(join(out, file)), { recursive: true });
  writeFileSync(join(out, file), css);
}
const kb = (s) => `${(Buffer.byteLength(s) / 1024).toFixed(0)} KB`;
console.log(`✔ ${relative(out)}/`);
for (const [file, css] of Object.entries(files)) console.log(`  ${file} (${kb(css)})`);
